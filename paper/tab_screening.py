"""
Emit the foundation-model screening table (paper Table 1) from the uniform screen.

Every row reports the same measured quantities at the same protocol (matched 10-seed tuned-head
single-arm probe, paired delta vs DINOv2, and the degeneracy diagnostics), read from
runs/screen/screen_results.json. Per-backbone metadata (objective, pretraining domain) are facts,
not measurements, so they live in META here; everything numeric comes from the JSON.

    bash scripts/run_screen.sh          # -> runs/screen/screen_results.json, then this script
    python paper/tab_screening.py       # -> paper/tab_screening.tex
"""
import argparse
import json
import os

_PAPER = os.path.dirname(os.path.abspath(__file__))
_REPO = os.path.dirname(_PAPER)
JSON = os.path.join(_REPO, "runs/screen/screen_results.json")

# (key in JSON, display, objective, pretrain domain, group) -- ordering + facts only
META = [
    ("dinov2",     "DINOv2",     "self-distill.",      "natural",    "core"),
    ("biomedclip", "BiomedCLIP", "contrastive",        "biomedical", "core"),
    ("sam",        "SAM",        "segmentation",       "natural",    "core"),
    ("phikon",     "Phikon",     "iBOT",               "pathology",  "core"),
    ("radiodino",  "RadioDINO",  "DINO",               "radiology",  "other"),
    ("arniqa",     "ARNIQA",     "IQA contrastive",    "natural",    "other"),
    ("sam2",       "SAM2",       "segmentation",       "natural",    "other"),
    ("mae_vit_b",  "MAE",        "masked recon.",      "natural",    "other"),
    ("brainiac",   "BrainIAC",   "SimCLR (3D)",        "brain MRI",  "other"),
    ("triad",      "Triad",      "masked recon. (3D)", "brain MRI",  "other"),
]
GROUP_ORDER = ["core", "other"]
GROUP_HDR = {"core": "Distilled / gated teachers (kept)",
             "other": "Other screened candidates"}


def credible(r: dict) -> bool:
    """Paired |t| >= 2.5 and |delta| > 0.002 (the starred rows)."""
    return r["delta"] is not None and abs(r["t"]) >= 2.5 and abs(r["delta"]) > 0.002


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", default=JSON, help="screen_results.json (lofi_radio/screen_probe.py)")
    ap.add_argument("--out", default=os.path.join(_PAPER, "tab_screening.tex"))
    args = ap.parse_args()
    blob = json.load(open(args.json))
    res, nseed = blob["results"], blob["n_seeds"]

    lines = [
        "% Foundation-model screening table.",
        "% Generated by paper/tab_screening.py from runs/screen/screen_results.json "
        f"({nseed}-seed uniform probe). Needs \\usepackage{{booktabs}}.",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Uniform frozen-feature screen of candidate backbones for ULF neonatal artifact "
        "grading. Every row is measured at ONE protocol: a single-arm probe with the tuned head, on "
        "the same subject-grouped folds and " + f"{nseed} seeds, " + "paired against DINOv2 (the "
        "anchor). $\\overline{|\\cos|}$ and eff-rank are the cheap degeneracy screen, reported as "
        "diagnostics only.}",
        "\\label{tab:screening}",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\small",
        "\\resizebox{\\textwidth}{!}{%",
        "\\begin{tabular}{lllccr@{\\,$\\pm$\\,}lr}",
        "\\toprule",
        "Backbone & Objective & Pretrain & $\\overline{|\\cos|}$ & eff-rk & "
        "\\multicolumn{2}{c}{Composite} & $\\Delta$ \\\\",
    ]

    meta_of = {key: (disp, obj, dom, group) for key, disp, obj, dom, group in META}
    for group in GROUP_ORDER:
        present = [k for k, *_ in META if k in res and meta_of[k][3] == group]
        if not present:
            continue
        present.sort(key=lambda k: -res[k]["composite"])      # rank within the group by composite
        lines.append("\\midrule")
        lines.append(f"\\multicolumn{{8}}{{l}}{{\\textit{{{GROUP_HDR[group]}}}}} \\\\")
        for key in present:
            disp, obj, dom, _ = meta_of[key]
            r = res[key]
            cos = f"{r['cos']:.2f}"
            eff = f"{r['eff_rank']:.3f}"
            comp, std = f"{r['composite']:.4f}", f"{r['composite_std']:.4f}"
            dcell = "---" if r["delta"] is None else f"{r['delta']:+.4f}" + ("$^\\ast$" if credible(r) else "")
            if credible(r) and r["delta"] > 0:                # credibly beats the anchor
                disp = f"\\textbf{{{disp}}}"
            lines.append(f"{disp} & {obj} & {dom} & {cos} & {eff} & {comp} & {std} & {dcell} \\\\")

    lines += [
        "\\bottomrule",
        "\\end{tabular}%",
        "}",
        "\\\\[2pt]",
        "{\\footnotesize $^\\ast$paired $|t|\\ge2.5$ and $|\\Delta|>0.002$.}",
        "\\end{table}",
    ]

    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {args.out}  ({sum(1 for k, *_ in META if k in res)} backbones)")


if __name__ == "__main__":
    main()
