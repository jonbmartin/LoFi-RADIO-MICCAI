"""
Emit the method-ablation table (paper Table 2): single FM / concat / gate / distilled student.

Reads the matched 10-seed tuned-head numbers written by lofi_radio/tri_probe.py:
  runs/tri_probe_fm/tri_metrics.json        -- singles + concat + gate over DINOv2/BiomedCLIP/SAM/Phikon
  runs/tri_probe_students/tri_metrics.json  -- distilled students (single-feature probes)
DINOv2-single is the shared anchor and must be identical across both runs.

    bash scripts/run_method_ablation.sh     # -> the two JSONs, then this script
    python paper/tab_method_ablation.py     # -> paper/tab_method_ablation.tex
"""
import json
import os

_PAPER = os.path.dirname(os.path.abspath(__file__))
_REPO = os.path.dirname(_PAPER)
ARTIFACTS = ["Noise", "Zipper", "Positioning", "Banding", "Motion", "Contrast", "Distortion"]
ABBR = ["Noise", "Zip.", "Pos.", "Band.", "Mot.", "Con.", "Dist."]

fm = json.load(open(os.path.join(_REPO, "runs/tri_probe_fm/tri_metrics.json")))["summary"]
st = json.load(open(os.path.join(_REPO, "runs/tri_probe_students/tri_metrics.json")))["summary"]

# (display name, source dict, key)
ROWS = [
    ("group", "Single frozen FM"),
    ("DINOv2",        fm, "DINOv2"),
    ("BiomedCLIP",    fm, "BiomedCLIP"),
    ("SAM",           fm, "SAM"),
    ("Phikon",        fm, "Phikon"),
    ("group", "Combination of all four FMs"),
    ("Concat",                       fm, "concat"),
    ("Gate (per-artifact router)",   fm, "gate"),
    ("group", "Distilled student (ours)"),
    ("Student~$\\leftarrow$~D+BMC",   st, "Student-DBMC"),
    ("\\quad +~Phikon teacher",       st, "Student-Phi"),
    ("\\quad +OpenNeuro corpus",      st, "Student-Phi-ds"),
]

data_rows = [(r[0], r[1][r[2]]) for r in ROWS if r[0] != "group"]

# per-column max (rounded to 3 dp) for bolding; composite max (4 dp)
col_max = [max(round(d["per_artifact"][a][0], 3) for _, d in data_rows) for a in ARTIFACTS]
comp_max = max(round(d["composite"], 4) for _, d in data_rows)


def fmt_art(v, mx):
    s = f"{v:.3f}"
    return f"\\textbf{{{s}}}" if round(v, 3) == mx else s


def fmt_comp(d):
    m, s = d["composite"], d["composite_std"]
    body = f"{m:.4f}\\,$\\pm$\\,{s:.4f}"
    return f"\\textbf{{{body}}}" if round(m, 4) == comp_max else body


lines = [
    "% Method ablation: Single FM / Concat / Gate / Distilled student.",
    "% Generated by paper/tab_method_ablation.py from tri_probe JSONs. Needs \\usepackage{booktabs}.",
    "\\begin{table}[t]",
    "\\centering",
    "\\caption{Comparison of single- and multi-backbone strategies for ULF neonatal artifact grading, "
    "evaluated using the matched 10-seed, subject-grouped five-fold protocol. Per-artifact and overall "
    "composite scores are reported as mean$\\pm$standard deviation, with the best value in each column "
    "shown in \\textbf{bold}. The distilled configurations are shown cumulatively, adding the Phikon "
    "teacher and then the exact-field OpenNeuro corpus to the DINOv2 and BiomedCLIP student.}",
    "\\label{tab:method_ablation}",
    "\\setlength{\\tabcolsep}{4.5pt}",
    "\\small",
    "\\resizebox{\\textwidth}{!}{%",
    "\\begin{tabular}{l" + "c" * len(ARTIFACTS) + "c}",
    "\\toprule",
    "Method & " + " & ".join(ABBR) + " & Composite \\\\",
]

for r in ROWS:
    if r[0] == "group":
        lines.append("\\midrule")
        lines.append(f"\\multicolumn{{{len(ARTIFACTS) + 2}}}{{l}}{{\\textit{{{r[1]}}}}} \\\\")
        continue
    disp, d = r[0], r[1][r[2]]
    cells = [fmt_art(d["per_artifact"][a][0], col_max[i]) for i, a in enumerate(ARTIFACTS)]
    lines.append(f"{disp} & " + " & ".join(cells) + f" & {fmt_comp(d)} \\\\")

lines += ["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}"]

out = os.path.join(_PAPER, "tab_method_ablation.tex")
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {out}")
print(f"anchor check: DINOv2 fm={fm['DINOv2']['composite']:.4f}  st={st['DINOv2']['composite']:.4f}")
